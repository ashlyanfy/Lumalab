function formatNumberWithSpaces(num){
  const s = Math.floor(Math.max(0, Number(num) || 0)).toString();
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

const GDP_RATE = 4004946.7275; // USD per second (IMF WEO 2026: 126.3T / 31536000)
const START_2026 = Date.UTC(2026, 0, 1, 0, 0, 0, 0);

function getGdpValue(){
  const elapsed = Math.max(0, (Date.now() - START_2026) / 1000);
  return elapsed * GDP_RATE;
}

function animateLiveValue(){
  const section = $('#livevalue');
  const numberEl = $('#liveValueNumber');
  if(!section || !numberEl) return;
  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if(reduceMotion){
    numberEl.textContent = formatNumberWithSpaces(getGdpValue());
    return;
  }
  let timerId = null;
  const io = new IntersectionObserver((entries) => {
    const entry = entries[0];
    if(entry.isIntersecting && !timerId){
      const target = getGdpValue();
      const duration = 1800;
      const start = Date.now();
      const tick = () => {
        const p = Math.min(1, (Date.now() - start) / duration);
        const eased = p < 1 ? 1 - Math.pow(1 - p, 3) : 1;
        numberEl.textContent = formatNumberWithSpaces(target * eased);
        if(p < 1){ requestAnimationFrame(tick); }
        else{
          timerId = setInterval(() => {
            numberEl.textContent = formatNumberWithSpaces(getGdpValue());
          }, 1000);
        }
      };
      requestAnimationFrame(tick);
    } else if(!entry.isIntersecting && timerId){
      clearInterval(timerId);
      timerId = null;
    }
  }, {threshold: 0.1});
  io.observe(section);
}

