async function main() {
  const slug = 'home';
  const page = await prisma.page.upsert({
    where: { slug },
    create: { slug, title: 'LumaLab — главная' },
    update: {},
  });

  // SEO defaults
  await prisma.seo.upsert({
    where: { pageId: page.id },
    create: {
      pageId: page.id,
      title: 'LumaLab | Equity Growth Partner',
      description:
        'LumaLab усиливает действующие цифровые продукты крупных компаний через AI, данные, продуктовую стратегию, NDA-процесс и партнёрскую модель роста.',
      keywords: 'lumalab, growth partner, equity, AI, продуктовый рост',
      ogImage: '/assets/image.jpg',
    },
    update: {},
  });

  // Get existing block types to skip duplicates
  const existing = await prisma.block.findMany({
    where: { pageId: page.id },
    select: { type: true },
  });
  const have = new Set(existing.map((b) => b.type));

  let order =
    (await prisma.block.aggregate({
      where: { pageId: page.id },
      _max: { order: true },
    }))._max.order ?? -1;

  let created = 0;
  for (const block of HOME_BLOCKS) {
    if (have.has(block.type)) {
      console.log(`[seed:cms] skip ${block.type} (already exists)`);
      continue;
    }
    order += 1;
    await prisma.block.create({
      data: {
        pageId: page.id,
        type: block.type,
        order,
        enabled: true,
        data: block.data as Prisma.InputJsonValue,
      },
    });
    console.log(`[seed:cms] + ${block.type}`);
    created += 1;
  }

  console.log('====================================================');
  console.log(`[seed:cms] page "${slug}" ready · ${created} new blocks`);
  console.log('====================================================');
}

main()
  .catch((e) => {
    console.error('[seed:cms] failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
